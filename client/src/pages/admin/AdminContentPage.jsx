import { useCallback, useEffect, useState } from 'react';
import * as adminService from '../../services/adminService.js';
import {
  AdminCard,
  AdminEmpty,
  AdminFilter,
  AdminLoading,
  AdminNotice,
  AdminPageHeader,
  AdminStatusBadge,
  adminErrorMessage,
  formatAdminDate,
} from '../../components/admin/AdminUI.jsx';

const contentTypes = ['STORY', 'ARTICLE', 'FAQ', 'PROGRAMME', 'ANNOUNCEMENT'];
const emptyContent = {
  type: 'ARTICLE',
  title: '',
  excerpt: '',
  body: '',
  image: '',
  published: false,
};

function ContentForm({ initial, onSave, onCancel, saving }) {
  const [values, setValues] = useState(initial || emptyContent);
  const update = (field, value) => setValues((current) => ({ ...current, [field]: value }));

  function submit(event) {
    event.preventDefault();
    onSave(values);
  }

  return (
    <form className="admin-card resource-admin-form" onSubmit={submit}>
      <div className="admin-card-heading">
        <div>
          <h2>{initial ? 'Edit content' : 'Create content'}</h2>
          <p>The URL slug is generated by the existing content service from the title.</p>
        </div>
      </div>
      <div className="resource-admin-form-grid">
        <AdminFilter label="Content type">
          <select value={values.type} onChange={(event) => update('type', event.target.value)}>
            {contentTypes.map((type) => <option key={type} value={type}>{type}</option>)}
          </select>
        </AdminFilter>
        <AdminFilter label="Title">
          <input required maxLength={220} value={values.title} onChange={(event) => update('title', event.target.value)} />
        </AdminFilter>
        <AdminFilter label="Image URL">
          <input type="url" maxLength={500} value={values.image} onChange={(event) => update('image', event.target.value)} placeholder="Optional" />
        </AdminFilter>
        <AdminFilter label="Excerpt">
          <textarea maxLength={500} rows={3} value={values.excerpt} onChange={(event) => update('excerpt', event.target.value)} />
        </AdminFilter>
        <AdminFilter label="Body">
          <textarea required maxLength={15000} rows={8} value={values.body} onChange={(event) => update('body', event.target.value)} />
        </AdminFilter>
        <label className="resource-publish-toggle">
          <input type="checkbox" checked={Boolean(values.published)} onChange={(event) => update('published', event.target.checked)} />
          Publish immediately
        </label>
      </div>
      <div className="admin-action-row">
        <button className="button button-primary" type="submit" disabled={saving}>
          {saving ? 'Saving…' : initial ? 'Save changes' : 'Create content'}
        </button>
        <button className="button button-secondary" type="button" onClick={onCancel} disabled={saving}>Cancel</button>
      </div>
    </form>
  );
}

export default function AdminContentPage() {
  const [state, setState] = useState({ loading: true, error: '', content: [] });
  const [search, setSearch] = useState('');
  const [editing, setEditing] = useState(null);
  const [creating, setCreating] = useState(false);
  const [processingId, setProcessingId] = useState('');
  const [saving, setSaving] = useState(false);
  const [notice, setNotice] = useState('');

  const load = useCallback(async () => {
    setState((current) => ({ ...current, loading: true, error: '' }));
    try {
      const result = await adminService.listAdminContent();
      setState({ loading: false, error: '', content: result.content || [] });
    } catch (error) {
      setState((current) => ({
        ...current,
        loading: false,
        error: adminErrorMessage(error, 'Could not load content.'),
      }));
    }
  }, []);

  useEffect(() => { load(); }, [load]);

  async function saveContent(values) {
    setSaving(true);
    setState((current) => ({ ...current, error: '' }));
    setNotice('');
    try {
      if (editing) {
        await adminService.updateAdminContent(editing.id, values);
        setNotice('Content changes saved.');
      } else {
        await adminService.createAdminContent(values);
        setNotice(values.published ? 'Content created and published.' : 'Content created as a draft.');
      }
      setCreating(false);
      setEditing(null);
      await load();
    } catch (error) {
      setState((current) => ({ ...current, error: adminErrorMessage(error, 'Could not save this content.') }));
    } finally {
      setSaving(false);
    }
  }

  async function togglePublished(item) {
    setProcessingId(item.id);
    setState((current) => ({ ...current, error: '' }));
    setNotice('');
    try {
      await adminService.updateAdminContent(item.id, { published: !item.published });
      setNotice(item.published ? 'Content unpublished.' : 'Content published.');
      await load();
    } catch (error) {
      setState((current) => ({ ...current, error: adminErrorMessage(error, 'Could not update publication status.') }));
    } finally {
      setProcessingId('');
    }
  }

  async function removeContent(item) {
    if (!window.confirm(`Delete "${item.title}"? This cannot be undone.`)) return;
    setProcessingId(item.id);
    setState((current) => ({ ...current, error: '' }));
    setNotice('');
    try {
      await adminService.deleteAdminContent(item.id);
      setNotice('Content deleted.');
      if (editing?.id === item.id) setEditing(null);
      await load();
    } catch (error) {
      setState((current) => ({ ...current, error: adminErrorMessage(error, 'Could not delete this content.') }));
    } finally {
      setProcessingId('');
    }
  }

  const filtered = state.content.filter((item) =>
    `${item.title} ${item.type} ${item.excerpt} ${item.slug}`
      .toLowerCase()
      .includes(search.trim().toLowerCase()),
  );

  return (
    <section className="admin-workspace resource-admin-page">
      <AdminPageHeader
        title="Content Management"
        description="Manage published stories, articles, FAQs, programmes, and announcements."
        actions={<button className="button button-secondary" type="button" onClick={load} disabled={state.loading}>Refresh</button>}
      />
      <AdminNotice kind="success">{notice}</AdminNotice>
      <AdminNotice onRetry={load}>{state.error}</AdminNotice>
      {!creating && !editing && (
        <div className="resource-admin-toolbar">
          <AdminFilter label="Search content">
            <input value={search} onChange={(event) => setSearch(event.target.value)} placeholder="Title, type, excerpt, or slug" />
          </AdminFilter>
          <button className="button button-primary" type="button" onClick={() => { setCreating(true); setNotice(''); }}>
            Create content
          </button>
        </div>
      )}
      {(creating || editing) && (
        <ContentForm
          key={editing?.id || 'new-content'}
          initial={editing}
          onSave={saveContent}
          onCancel={() => { setCreating(false); setEditing(null); }}
          saving={saving}
        />
      )}
      <AdminCard className="resource-admin-list">
        <div className="admin-card-heading">
          <div><h2>Content</h2><p>{state.content.length} total</p></div>
        </div>
        {state.loading ? <AdminLoading>Loading content…</AdminLoading> : !state.content.length ? (
          <AdminEmpty title="No content yet">Create a draft to start publishing Academy content.</AdminEmpty>
        ) : !filtered.length ? (
          <AdminEmpty title="No matching content">Try another search term.</AdminEmpty>
        ) : (
          <div className="resource-admin-grid">
            {filtered.map((item) => (
              <article className="resource-admin-item" key={item.id}>
                {item.image && <img src={item.image} alt="" loading="lazy" />}
                <div className="resource-admin-item-body">
                  <div className="resource-admin-item-status">
                    <AdminStatusBadge status={item.published ? 'PUBLISHED' : 'DRAFT'} />
                    <span>{item.type}</span>
                  </div>
                  <h3>{item.title}</h3>
                  <p>{item.excerpt || item.body}</p>
                  <div className="resource-admin-meta">
                    <span>/{item.slug}</span>
                    <span>Updated {formatAdminDate(item.updatedAt)}</span>
                  </div>
                  <div className="admin-action-row">
                    <button className="button button-secondary" type="button" disabled={processingId === item.id} onClick={() => { setEditing(item); setCreating(false); setNotice(''); }}>
                      Edit
                    </button>
                    <button className="button button-secondary" type="button" disabled={processingId === item.id} onClick={() => togglePublished(item)}>
                      {processingId === item.id ? 'Saving…' : item.published ? 'Unpublish' : 'Publish'}
                    </button>
                    <button className="button admin-button-danger" type="button" disabled={processingId === item.id} onClick={() => removeContent(item)}>
                      Delete
                    </button>
                  </div>
                </div>
              </article>
            ))}
          </div>
        )}
      </AdminCard>
    </section>
  );
}
